const metaLine = (e) => [e.date, e.week, e.weather, e.mood].filter(Boolean).map(esc).join(' · ');

function entryPage(e, i, all) {
  const prev = all[i - 1], next = all[i + 1];
  const pager = (x, dir) => x
    ? `<a class="diary-pager__link glass" href="${x.slug}.html"${dir === 'next' ? ' data-dir="next"' : ''}>
          <span class="diary-pager__label">${dir === 'prev' ? '← 前一篇' : '后一篇 →'}</span>
          <span class="diary-pager__title">${esc(x.title || x.cnDate)}</span>
        </a>`
    : '<span></span>';
  return page({
    title: `${e.title || e.cnDate} · 日记 · 贾涵翌`,
    desc: excerpt(e.body, 80) || `${e.cnDate}的日记`,
    url: `${SITE}/diary/${e.slug}.html`,
    type: 'article',
    back: { href: './', text: '全部日记' },
    main: `    <header class="section-head">
      <p class="eyebrow" data-reveal>Diary · No.${i + 1}</p>
      <h1 class="h2" data-reveal>${esc(e.title || e.cnDate)}</h1>
      <p class="post__meta" data-reveal>${metaLine(e)}</p>
    </header>
    <article class="prose glass" data-reveal>
${markdown(e.body)}
    </article>
    <nav class="diary-pager" aria-label="翻页" data-reveal>
      ${pager(prev, 'prev')}
      ${pager(next, 'next')}
    </nav>`,
  });
}

function indexPage(all) {
  const latest = all[all.length - 1];
  let streak = 0;
  if (latest) {
    const days = [...new Set(all.map((e) => e.date))].reverse();
    streak = 1;
    for (let k = 1; k < days.length && dayDiff(days[k - 1], days[k]) === 1; k++) streak++;
  }
  const months = new Map();
  [...all].reverse().forEach((e) => {
    const key = e.date.slice(0, 7);
    if (!months.has(key)) months.set(key, []);
    months.get(key).push(e);
  });
  const body = all.length
    ? [...months].map(([key, list]) => {
      const [y, m] = key.split('-');
      return `    <section class="diary-month">
      <h2 class="h3 diary-month__title" data-reveal>${y}年${Number(m)}月<span>${list.length} 篇</span></h2>
      <ul class="list glass" data-reveal>
${list.map((e) => `        <li>
          <a class="list-item" href="${e.slug}.html">
            <time class="list-item__meta" datetime="${e.date}">${e.date.slice(5)} ${e.week.replace('星期', '周')}</time>
            <span class="list-item__title">${e.mood ? `<span class="diary-mood">${esc(e.mood)}</span>` : ''}${esc(e.title || excerpt(e.body))}</span>
            <svg class="icon"><use href="#i-arrow-right"/></svg>
          </a>
        </li>`).join('\n')}
      </ul>
    </section>`;
    }).join('\n')
    : `    <div class="diary-empty glass" data-reveal>
      <p class="h3">还没有日记</p>
      <p class="muted">第一篇就从今天开始吧。</p>
    </div>`;
  return page({
    title: '日记 · 贾涵翌',
    desc: '贾涵翌的日记，记录每天的一点生活和想法。',
    url: `${SITE}/diary/`,
    back: { href: '../', text: '返回主页' },
    main: `    <header class="section-head">
      <p class="eyebrow" data-reveal>Diary</p>
      <h1 class="h2" data-reveal>日记</h1>
      <p class="section-head__desc" data-reveal>每天的一点记录。</p>
${all.length ? `      <div class="cluster diary-stats" data-reveal>
        <span class="chip">共 ${all.length} 篇</span>
        <span class="chip">连续 ${streak} 天</span>
        <span class="chip">最近 ${latest.date}</span>
      </div>` : ''}
    </header>
${body}`,
  });
}

// ---------- sitemap ----------
function sitemap(all) {
  const today = new Date().toLocaleDateString('sv-SE');   // 本地日期 YYYY-MM-DD
  const urls = [[`${SITE}/`, today]];
  const posts = path.join(ROOT, 'posts');
  if (fs.existsSync(posts)) fs.readdirSync(posts).filter((f) => f.endsWith('.html')).sort().forEach((f) => {
    const html = fs.readFileSync(path.join(posts, f), 'utf8');
    const d = (html.match(/class="post__meta"[^>]*>\s*(\d{4}-\d{2}-\d{2})/) || [])[1];
    urls.push([`${SITE}/posts/${f}`, d]);
  });
  urls.push([`${SITE}/diary/`, all.length ? all[all.length - 1].date : today]);
  all.forEach((e) => urls.push([`${SITE}/diary/${e.slug}.html`, e.date]));
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- 由 tools/build-diary.mjs 自动生成，请不要手动修改 -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(([u, d]) => `  <url><loc>${u}</loc>${d ? `<lastmod>${d}</lastmod>` : ''}</url>`).join('\n')}
</urlset>
`;
}

// ---------- 生成 ----------
const all = readEntries();
fs.mkdirSync(OUT, { recursive: true });
const keep = new Set(all.map((e) => `${e.slug}.html`));
for (const f of fs.readdirSync(OUT)) {        // 删掉源文件已不存在的旧页面（只删本脚本生成的）
  if (/^\d{4}-\d{2}-\d{2}.*\.html$/.test(f) && !keep.has(f)
      && fs.readFileSync(path.join(OUT, f), 'utf8').includes(MARK)) fs.unlinkSync(path.join(OUT, f));
}
all.forEach((e, i) => fs.writeFileSync(path.join(OUT, `${e.slug}.html`), entryPage(e, i, all)));
fs.writeFileSync(path.join(OUT, 'index.html'), indexPage(all));
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), sitemap(all));
console.log(`日记：${all.length} 篇 → diary/index.html${all.length ? `，最新 ${all[all.length - 1].date}` : ''}`);
