#!/usr/bin/env node
// =========================================================
// 日记生成器（无依赖）
//   源文件：diary/src/YYYY-MM-DD.md （同一天多篇：YYYY-MM-DD-2.md）
//   生成：  diary/YYYY-MM-DD.html、diary/index.html、sitemap.xml
//   用法：  node tools/build-diary.mjs
//
// 源文件格式（--- 之间的信息都可以省略）：
//   ---
//   title: 今天的标题
//   weather: 晴
//   mood: 😊
//   ---
//   正文，支持 Markdown：**粗体**、*斜体*、[链接](https://...)、
//   ![图片](img/xxx.jpg)、- 列表、1. 列表、> 引用、## 小标题、---
// =========================================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'diary', 'src');
const OUT = path.join(ROOT, 'diary');
const SITE = 'https://jiahanyi1218.me';
const MARK = '<!-- generated by tools/build-diary.mjs -->';
const WEEK = ['星期日', '星期一', '星期二', '星期三', '星期四', '星期五', '星期六'];

// ---------- 工具 ----------
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const safeUrl = (u) => {
  u = u.trim();
  if (/^(https?:|mailto:)/i.test(u)) return u;
  if (/^[a-z][a-z0-9+.-]*:/i.test(u)) return null;   // 拦截 javascript: 等危险协议
  return u;                                          // 相对路径
};
const parseDate = (s) => { const [y, m, d] = s.split('-').map(Number); return new Date(Date.UTC(y, m - 1, d)); };
const dayDiff = (a, b) => Math.round((parseDate(a) - parseDate(b)) / 86400000);

// ---------- Markdown（够写日记用的子集；所有文字先转义，杜绝注入 HTML） ----------
function inline(text) {
  const codes = [];
  let s = esc(text).replace(/`([^`]+)`/g, (_, c) => `\u0000${codes.push(c) - 1}\u0000`);
  s = s.replace(/!\[([^\]]*)\]\(([^)\s]+)\)/g, (m, alt, src) => {
    const u = safeUrl(src.replace(/&amp;/g, '&'));
    return u ? `<img src="${esc(u)}" alt="${alt}" loading="lazy" />` : alt;
  });
  s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (m, t, href) => {
    const u = safeUrl(href.replace(/&amp;/g, '&'));
    if (!u) return t;
    const ext = /^https?:/i.test(u) ? ' target="_blank" rel="noopener noreferrer"' : '';
    return `<a href="${esc(u)}"${ext}>${t}</a>`;
  });
  s = s.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>').replace(/(^|[^*])\*([^*\s][^*]*)\*/g, '$1<em>$2</em>');
  s = s.replace(/~~([^~]+)~~/g, '<del>$1</del>');
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${codes[i]}</code>`);
}

function markdown(md) {
  const lines = md.replace(/\r\n?/g, '\n').split('\n');
  const out = [];
  let para = [], list = null, quote = [], fence = null;
  const flushPara = () => { if (para.length) out.push(`<p>${para.map(inline).join('<br />')}</p>`); para = []; };
  const flushList = () => { if (list) out.push(`<${list.tag}>${list.items.map((i) => `<li>${inline(i)}</li>`).join('')}</${list.tag}>`); list = null; };
  const flushQuote = () => { if (quote.length) out.push(`<blockquote>${quote.map(inline).join('<br />')}</blockquote>`); quote = []; };
  const flushAll = () => { flushPara(); flushList(); flushQuote(); };

  for (const raw of lines) {
    const line = raw.trimEnd();
    if (fence) {
      if (/^```/.test(line)) { out.push(`<pre><code>${esc(fence.join('\n'))}</code></pre>`); fence = null; }
      else fence.push(raw);
      continue;
    }
    let m;
    if (/^```/.test(line)) { flushAll(); fence = []; }
    else if (!line.trim()) flushAll();
    else if ((m = line.match(/^#{1,4}\s+(.*)$/))) { flushAll(); out.push(`<h3>${inline(m[1])}</h3>`); }
    else if (/^(-{3,}|\*{3,})$/.test(line.trim())) { flushAll(); out.push('<hr />'); }
    else if ((m = line.match(/^>\s?(.*)$/))) { flushPara(); flushList(); quote.push(m[1]); }
    else if ((m = line.match(/^\s*[-*+]\s+(.*)$/)) || (m = line.match(/^\s*\d+[.)]\s+(.*)$/))) {
      flushPara(); flushQuote();
      const tag = /^\s*\d/.test(line) ? 'ol' : 'ul';
      if (!list || list.tag !== tag) { flushList(); list = { tag, items: [] }; }
      list.items.push(m[1]);
    } else { flushList(); flushQuote(); para.push(line.trim()); }
  }
  if (fence) out.push(`<pre><code>${esc(fence.join('\n'))}</code></pre>`);
  flushAll();
  return out.join('\n');
}

const plain = (md) => md.replace(/```[\s\S]*?```/g, ' ').replace(/^\s*\d+[.)]\s+/gm, '').replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
  .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1').replace(/[#>*_`~-]/g, ' ').replace(/\s+/g, ' ').trim();
const excerpt = (md, n = 36) => { const t = plain(md); return [...t].length > n ? [...t].slice(0, n).join('') + '…' : t; };

// ---------- 读取源文件 ----------
function readEntries() {
  if (!fs.existsSync(SRC)) return [];
  return fs.readdirSync(SRC).filter((f) => /^\d{4}-\d{2}-\d{2}(-[\w-]+)?\.md$/.test(f)).sort().map((f) => {
    const slug = f.replace(/\.md$/, '');
    const date = slug.slice(0, 10);
    let text = fs.readFileSync(path.join(SRC, f), 'utf8').replace(/^﻿/, '');
    const meta = {};
    const fm = text.match(/^---\n([\s\S]*?)\n---\n?/);
    if (fm) {
      fm[1].split('\n').forEach((l) => { const i = l.indexOf(':'); if (i > 0) meta[l.slice(0, i).trim()] = l.slice(i + 1).trim(); });
      text = text.slice(fm[0].length);
    }
    const d = parseDate(date);
    return {
      slug, date, body: text.trim(), title: meta.title || '', weather: meta.weather || '', mood: meta.mood || '',
      week: WEEK[d.getUTCDay()],
      cnDate: `${d.getUTCFullYear()}年${d.getUTCMonth() + 1}月${d.getUTCDate()}日`,
    };
  });
}

